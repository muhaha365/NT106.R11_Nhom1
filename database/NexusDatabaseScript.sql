CREATE DATABASE ChatAppDB
USE ChatAppDB;
GO

CREATE TABLE Users (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    Username VARCHAR(50) NOT NULL UNIQUE,
    PasswordHash VARCHAR(256) NOT NULL,
    DisplayName NVARCHAR(100) NOT NULL,
    IsOnline BIT DEFAULT 0,
    CreatedAt DATETIME DEFAULT GETDATE()
);

CREATE TABLE Groups (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    GroupName NVARCHAR(100) NOT NULL,
    CreatedBy INT NOT NULL FOREIGN KEY REFERENCES Users(Id),
    CreatedAt DATETIME DEFAULT GETDATE()
);

CREATE TABLE Messages (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    SenderId INT NOT NULL FOREIGN KEY REFERENCES Users(Id),
    ReceiverId INT NULL FOREIGN KEY REFERENCES Users(Id),
    GroupId INT NULL FOREIGN KEY REFERENCES Groups(Id),
    Content NVARCHAR(MAX) NULL,
    SendTime DATETIME DEFAULT GETDATE()
);

CREATE TABLE Friends (
    UserId1 INT NOT NULL FOREIGN KEY REFERENCES Users(Id),
    UserId2 INT NOT NULL FOREIGN KEY REFERENCES Users(Id),
    Status VARCHAR(20) DEFAULT 'Pending',
    CreatedAt DATETIME DEFAULT GETDATE(),
    PRIMARY KEY (UserId1, UserId2)
);

